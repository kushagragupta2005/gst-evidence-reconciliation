"""Render the immutable-preregistration scorecard from recorded artifacts."""
import json
from pathlib import Path

v2 = json.loads(Path('reports/v2_seed_c_results.json').read_text())
tradeoff = json.loads(Path('reports/v2_threshold_tradeoff.json').read_text())
row = next(item for item in tradeoff['rows'] if item['threshold'] == .05)

def pct(value):
    return 'n/a' if value is None else f'{value * 100:.2f}%'

def ci(metric, name):
    bounds = metric['ci95'].get(name)
    return pct(metric[name]) + (f' [{pct(bounds[0])}, {pct(bounds[1])}]' if bounds else '')

monthly, factory = v2['factory_month'], v2['factory']
lines = [
    '<!-- Generated by scripts/render_preregistration_scorecard.py. -->',
    '# Preregistration scorecard', '',
    'The preregistration itself is immutable at `docs/preregistration.md`. This scorecard reports status against it; a PASS means the measurement or engineering control exists, not that the synthetic result generalises to real GST enforcement.', '',
    '| Criterion | Status | Measured value or evidence |', '|---|---|---|',
    f'| Calibration uses Seed A only | PASS | V2-A selected threshold {v2["protocol"]["threshold"]:.3f} and K={v2["factory_queue"]["k"]}; V2-B/C were held out. |',
    f'| Factory-month headline metrics with clustered CIs | PASS | Recall {ci(monthly,"recall")}; FPR {ci(monthly,"fpr")}; precision {ci(monthly,"precision")}. |',
    f'| Factory queue metrics with clustered CIs | PASS | Recall {ci(factory,"recall")}; FPR {ci(factory,"fpr")}; precision {ci(factory,"precision")}; queue {v2["factory_queue"]["queue_size"]}. |',
    f'| Evasive-case recall published | PASS | {ci(v2["evasive"]["factory_month"],"recall")} on V2-C. |',
    f'| Per-decoy FPR published | PASS | Six decoy groups in `reports/v2_seed_c_results.json`; new-supplier FPR {pct(v2["fpr_by_decoy"]["factory_month"]["new_supplier_onboarding"]["fpr"])}. |',
    f'| Threshold trade-off published | PASS | At 5%: recall {pct(row["monthly"]["recall"])}, FPR {pct(row["monthly"]["fpr"])}, evasive recall {pct(row["evasive"]["recall"])}, K=2 queue {row["factory_queue_size_k2"]}. |',
    '| Label isolation | PASS | `tests/test_engine.py` blocks detector/dashboard label references; dashboard DB user was denied `GST_EVALUATION.TRUTH`. |',
    '| Ranking matches evaluation | PASS | Source-level rank-order test passes. |',
    f'| Stock check has measurable contribution | PASS | V2-C stock-check recall {ci(v2["per_check"]["stock_rollforward"],"recall")}; planted mechanics only. |',
    '| Verified-document clearing and wrong-clear rate | FAIL | Uploaded-evidence table and wrong-clear experiment are not implemented. |',
    '| Realistic prevalence by regenerated/resampled populations | FAIL | Existing prevalence table is analytic adjustment only. |',
    '| Five held-out seeds | FAIL | Two V2 held-out seeds: B and C. |',
    '| Fair repeated Exasol/pandas/DuckDB benchmark | FAIL | Existing comparison is not a fair multi-engine repeated benchmark. |',
    '| 50+ session mixed-workload concurrency | FAIL | Existing run is eight local guarded queries only. |',
    '| Successful UDF or MCP transcript | FAIL | Neither has a successful published transcript/test. |',
    '| Clean-machine from-scratch reproduction | FAIL | Existing check reused an installed Exasol runtime. |',
    '| Full-scale V2 benchmark | FAIL | The 20.98M-row benchmark predates V2 stock/ranking changes. |',
]
Path('docs/PREREGISTRATION_SCORECARD.md').write_text('\n'.join(lines) + '\n')
