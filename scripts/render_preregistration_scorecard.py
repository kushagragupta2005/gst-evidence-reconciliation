"""Render the development-only scorecard without promoting seen seeds."""
import json
from pathlib import Path


def pct(value):
    return 'n/a' if value is None else f'{value * 100:.2f}%'


def ci(metric, name):
    bounds = metric['ci95'].get(name)
    point = pct(metric[name])
    return point if not bounds else f'{point} [{pct(bounds[0])}, {pct(bounds[1])}]'


v2 = json.loads(Path('reports/v2_seed_c_results.json').read_text())
tradeoff = json.loads(Path('reports/v2_threshold_tradeoff.json').read_text())
row = next(item for item in tradeoff['rows'] if item['threshold'] == .05)
monthly, factory = v2['factory_month'], v2['factory']
lines = [
    '<!-- Generated by scripts/render_preregistration_scorecard.py. -->',
    '# Preregistration scorecard', '',
    'The immutable original protocol is `docs/preregistration.md`. V2-B, V2-C and the attribution seeds are **DEV** because they have been inspected during development. Their figures below are retained for audit only; they are not current held-out submission claims.', '',
    '| Criterion | Status | Measured value or evidence |', '|---|---|---|',
    f'| V2 factory-month metrics retained | DEV | Recall {ci(monthly, "recall")}; FPR {ci(monthly, "fpr")}; precision {ci(monthly, "precision")}. |',
    f'| V2 factory queue metrics retained | DEV | Recall {ci(factory, "recall")}; FPR {ci(factory, "fpr")}; precision {ci(factory, "precision")}; queue {v2["factory_queue"]["queue_size"]}. |',
    f'| V2 evasive-case recall retained | DEV | {ci(v2["evasive"]["factory_month"], "recall")}. |',
    f'| V2 threshold trade-off retained | DEV | At 5%: recall {pct(row["monthly"]["recall"])}, FPR {pct(row["monthly"]["fpr"])}, queue {row["factory_queue_size_k2"]}. |',
    '| Label isolation | VERIFIED | Offline tests block detector and dashboard outcome-label references. |',
    '| Ranking matches evaluation | VERIFIED | Source-level rank-order test passes. |',
    '| Stock scenario creates observable stock gaps | VERIFIED | Generator test requires all three active cheat types to break the stock identity. |',
    '| Verified-document clearing and wrong-clear rate | NOT-IMPLEMENTED | No uploaded-evidence table or wrong-clear experiment. |',
    '| Regenerated realistic-prevalence population | NOT-IMPLEMENTED | Existing table is analytic adjustment only. |',
    '| Fresh post-change held-out suite | NOT-IMPLEMENTED | V2 and attribution seeds are DEV; a new preregistration is required first. |',
    '| Fair repeated database and dataframe benchmark | NOT-IMPLEMENTED | Existing comparison is not a fair multi-engine repeated benchmark. |',
    '| Large mixed-workload concurrency | NOT-IMPLEMENTED | Existing run is limited local evidence. |',
    '| Advanced database extension | NOT-IMPLEMENTED | No successful dated transcript and test. |',
    '| Clean-machine from-scratch reproduction | NOT-IMPLEMENTED | Existing check reused an installed local runtime. |',
    '| Full-scale current-detector benchmark | NOT-IMPLEMENTED | Existing full-scale workload predates the current detector. |',
]
Path('docs/PREREGISTRATION_SCORECARD.md').write_text('\n'.join(lines) + '\n')
