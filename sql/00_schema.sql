CREATE SCHEMA IF NOT EXISTS GST_EVIDENCE;

CREATE OR REPLACE TABLE GST_EVIDENCE.FACTORIES (
  FACTORY_ID VARCHAR(20), NAME VARCHAR(200), ADDRESS VARCHAR(300), PHONE VARCHAR(30),
  VEHICLE_PLATE VARCHAR(20), GROUND_TRUTH VARCHAR(20), SCENARIO VARCHAR(40)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.SUPPLIERS (
  SUPPLIER_ID VARCHAR(20), NAME VARCHAR(200), ADDRESS VARCHAR(300), PHONE VARCHAR(30),
  LINKED_FACTORY_ID VARCHAR(20)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.FACTORY_MONTH (
  FACTORY_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7), PRODUCT VARCHAR(40), OPENING_STOCK DECIMAL(18,2),
  PURCHASES_KG DECIMAL(18,2), PURCHASES_FINISHED DECIMAL(18,2), DECLARED_OUTPUT DECIMAL(18,2), DECLARED_DISPATCH DECIMAL(18,2),
  CLOSING_STOCK DECIMAL(18,2), POWER_KWH DECIMAL(18,2), OPERATING_HOURS DECIMAL(18,2)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.INVOICES (
  INVOICE_ID VARCHAR(40), FACTORY_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7),
  QUANTITY DECIMAL(18,2), INVOICE_VALUE DECIMAL(18,2)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.PURCHASE_INVOICES (
  PURCHASE_INVOICE_ID VARCHAR(45), BUYER_FACTORY_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7), SUPPLIER_ID VARCHAR(20),
  QUANTITY DECIMAL(18,2), INVOICE_VALUE DECIMAL(18,2)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.EWAY_BILLS (
  EWAY_ID VARCHAR(50), FACTORY_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7),
  QUANTITY DECIMAL(18,2), VEHICLE_PLATE VARCHAR(20)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.SUPPLIER_RETURNS (
  SUPPLIER_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7), DECLARED_SALES_KG DECIMAL(18,2)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.BANK_ENTRIES (
  TRANSACTION_ID VARCHAR(50), FACTORY_ID VARCHAR(20), PERIOD_MONTH VARCHAR(7), AMOUNT DECIMAL(18,2)
);
CREATE OR REPLACE TABLE GST_EVIDENCE.MACHINES (
  MACHINE_ID VARCHAR(30), FACTORY_ID VARCHAR(20), INSTALLED_MONTH VARCHAR(7), RATED_UNITS_MONTH DECIMAL(18,2)
);
