-- Every view exposes entity, period, expected, observed, gap, and evidence detail.
CREATE OR REPLACE VIEW GST_EVIDENCE.V_MATERIAL_OUTPUT AS
SELECT m.FACTORY_ID, m.PERIOD_MONTH, 'material_output' AS CHECK_FAMILY,
       m.PURCHASES_KG * 0.8 AS EXPECTED, m.DECLARED_OUTPUT AS OBSERVED,
       m.PURCHASES_KG * 0.8 - m.DECLARED_OUTPUT AS GAP,
       'purchases_kg=' || m.PURCHASES_KG || ', power_kwh=' || m.POWER_KWH || ', operating_hours=' || m.OPERATING_HOURS AS EVIDENCE,
       CASE WHEN m.POWER_KWH > m.DECLARED_OUTPUT * 5.5
            THEN 'contradicting evidence' ELSE 'needs human review' END AS DISCREPANCY_CLASS
FROM GST_EVIDENCE.FACTORY_MONTH m
WHERE ABS(m.PURCHASES_KG * 0.8 - m.DECLARED_OUTPUT) > 100
   OR (m.POWER_KWH > m.DECLARED_OUTPUT * 5.5 AND m.DECLARED_OUTPUT > 0);

CREATE OR REPLACE VIEW GST_EVIDENCE.V_DISPATCH_INVOICE AS
SELECT e.FACTORY_ID, e.PERIOD_MONTH, 'dispatch_invoice' AS CHECK_FAMILY,
       SUM(e.QUANTITY) AS EXPECTED, COALESCE(SUM(i.QUANTITY), 0) AS OBSERVED,
       SUM(e.QUANTITY) - COALESCE(SUM(i.QUANTITY), 0) AS GAP,
       'eway_qty=' || SUM(e.QUANTITY) || ', invoice_qty=' || COALESCE(SUM(i.QUANTITY), 0) || ', bank_inflow=' || COALESCE(MAX(b.AMOUNT), 0) AS EVIDENCE,
       CASE WHEN COALESCE(SUM(i.INVOICE_ID_COUNT), 0) = 0 THEN 'missing documents' ELSE 'mismatch' END AS DISCREPANCY_CLASS
FROM (
  SELECT FACTORY_ID, PERIOD_MONTH, SUM(QUANTITY) QUANTITY FROM GST_EVIDENCE.EWAY_BILLS GROUP BY FACTORY_ID, PERIOD_MONTH
) e
LEFT JOIN (
  SELECT FACTORY_ID, PERIOD_MONTH, SUM(QUANTITY) QUANTITY, COUNT(*) INVOICE_ID_COUNT
  FROM GST_EVIDENCE.INVOICES GROUP BY FACTORY_ID, PERIOD_MONTH
) i ON i.FACTORY_ID=e.FACTORY_ID AND i.PERIOD_MONTH=e.PERIOD_MONTH
LEFT JOIN (
  SELECT FACTORY_ID, PERIOD_MONTH, SUM(AMOUNT) AS AMOUNT
  FROM GST_EVIDENCE.BANK_ENTRIES
  GROUP BY FACTORY_ID, PERIOD_MONTH
) b ON b.FACTORY_ID=e.FACTORY_ID AND b.PERIOD_MONTH=e.PERIOD_MONTH
GROUP BY e.FACTORY_ID, e.PERIOD_MONTH
HAVING ABS(SUM(e.QUANTITY) - COALESCE(SUM(i.QUANTITY), 0)) > 100;

CREATE OR REPLACE VIEW GST_EVIDENCE.V_STOCK_ROLLFORWARD AS
SELECT FACTORY_ID, PERIOD_MONTH, 'stock_rollforward' AS CHECK_FAMILY,
       OPENING_STOCK + PURCHASES_FINISHED + DECLARED_OUTPUT - DECLARED_DISPATCH AS EXPECTED,
       CLOSING_STOCK AS OBSERVED,
       OPENING_STOCK + PURCHASES_FINISHED + DECLARED_OUTPUT - DECLARED_DISPATCH - CLOSING_STOCK AS GAP,
       'opening=' || OPENING_STOCK || ', finished_purchases=' || PURCHASES_FINISHED || ', declared_output=' || DECLARED_OUTPUT || ', dispatch=' || DECLARED_DISPATCH || ', closing=' || CLOSING_STOCK AS EVIDENCE,
       'mismatch' AS DISCREPANCY_CLASS
FROM GST_EVIDENCE.FACTORY_MONTH
WHERE ABS(OPENING_STOCK + PURCHASES_FINISHED + DECLARED_OUTPUT - DECLARED_DISPATCH - CLOSING_STOCK) > 100;

CREATE OR REPLACE VIEW GST_EVIDENCE.V_SUPPLIER_LOOP AS
SELECT i.BUYER_FACTORY_ID AS FACTORY_ID, i.PERIOD_MONTH, 'supplier_chain' AS CHECK_FAMILY,
       m.PURCHASES_KG AS EXPECTED, r.DECLARED_SALES_KG AS OBSERVED,
       m.PURCHASES_KG-r.DECLARED_SALES_KG AS GAP,
       'supplier=' || i.SUPPLIER_ID || ', chain=' || i.BUYER_FACTORY_ID || '>' || s1.LINKED_FACTORY_ID || '>' || s2.LINKED_FACTORY_ID || '>' || s3.LINKED_FACTORY_ID || ', purchased_kg=' || m.PURCHASES_KG || ', supplier_return_kg=' || r.DECLARED_SALES_KG AS EVIDENCE,
       'supplier issue' AS DISCREPANCY_CLASS
FROM GST_EVIDENCE.PURCHASE_INVOICES i
JOIN GST_EVIDENCE.SUPPLIERS s1 ON s1.SUPPLIER_ID=i.SUPPLIER_ID
JOIN GST_EVIDENCE.PURCHASE_INVOICES i2 ON i2.BUYER_FACTORY_ID=s1.LINKED_FACTORY_ID AND i2.PERIOD_MONTH=i.PERIOD_MONTH
JOIN GST_EVIDENCE.SUPPLIERS s2 ON s2.SUPPLIER_ID=i2.SUPPLIER_ID
JOIN GST_EVIDENCE.PURCHASE_INVOICES i3 ON i3.BUYER_FACTORY_ID=s2.LINKED_FACTORY_ID AND i3.PERIOD_MONTH=i.PERIOD_MONTH
JOIN GST_EVIDENCE.SUPPLIERS s3 ON s3.SUPPLIER_ID=i3.SUPPLIER_ID AND s3.LINKED_FACTORY_ID=i.BUYER_FACTORY_ID
JOIN GST_EVIDENCE.FACTORY_MONTH m ON m.FACTORY_ID=i.BUYER_FACTORY_ID AND m.PERIOD_MONTH=i.PERIOD_MONTH
JOIN GST_EVIDENCE.SUPPLIER_RETURNS r ON r.SUPPLIER_ID=i.SUPPLIER_ID AND r.PERIOD_MONTH=i.PERIOD_MONTH
WHERE ABS(m.PURCHASES_KG-r.DECLARED_SALES_KG) > 100;

CREATE OR REPLACE VIEW GST_EVIDENCE.V_ALL_EVIDENCE AS
SELECT FACTORY_ID, PERIOD_MONTH, CHECK_FAMILY, EXPECTED, OBSERVED, GAP, EVIDENCE, DISCREPANCY_CLASS FROM GST_EVIDENCE.V_MATERIAL_OUTPUT
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH, CHECK_FAMILY, EXPECTED, OBSERVED, GAP, EVIDENCE, DISCREPANCY_CLASS FROM GST_EVIDENCE.V_DISPATCH_INVOICE
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH, CHECK_FAMILY, EXPECTED, OBSERVED, GAP, EVIDENCE, DISCREPANCY_CLASS FROM GST_EVIDENCE.V_STOCK_ROLLFORWARD
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH, CHECK_FAMILY, EXPECTED, OBSERVED, GAP, EVIDENCE, DISCREPANCY_CLASS FROM GST_EVIDENCE.V_SUPPLIER_LOOP;

-- Two separate check families are required for a ranked case.
CREATE OR REPLACE VIEW GST_EVIDENCE.V_RANKED_CASES AS
SELECT m.FACTORY_ID, m.PERIOD_MONTH,
       COALESCE(a.SIGNAL_COUNT, 0) AS SIGNAL_COUNT,
       COALESCE(a.EVIDENCE_COUNT, 0) AS EVIDENCE_COUNT,
       COALESCE(a.TOTAL_ABSOLUTE_GAP, 0) AS TOTAL_ABSOLUTE_GAP,
       CASE WHEN COALESCE(a.SIGNAL_COUNT, 0) >= 2 THEN 'prioritise'
            WHEN COALESCE(a.SIGNAL_COUNT, 0) = 1 THEN 'review only'
            ELSE 'clear' END AS STATUS
FROM GST_EVIDENCE.FACTORY_MONTH m
LEFT JOIN (
  SELECT FACTORY_ID, PERIOD_MONTH, COUNT(DISTINCT CHECK_FAMILY) AS SIGNAL_COUNT,
         COUNT(*) AS EVIDENCE_COUNT, SUM(ABS(GAP)) AS TOTAL_ABSOLUTE_GAP
  FROM GST_EVIDENCE.V_ALL_EVIDENCE
  GROUP BY FACTORY_ID, PERIOD_MONTH
) a ON a.FACTORY_ID=m.FACTORY_ID AND a.PERIOD_MONTH=m.PERIOD_MONTH;
