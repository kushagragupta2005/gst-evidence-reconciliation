-- Labels are never referenced by detection. Each ratio is dimensionless.
CREATE OR REPLACE VIEW GST_EVIDENCE.V_LEDGER AS
SELECT m.*, i.INVOICE_QTY, COALESCE(i.INVOICE_VALUE,0) INVOICE_VALUE,
       COALESCE(e.DISPATCH_QTY,0) DISPATCH_QTY, COALESCE(e.REUSE_RATIO,0) REUSE_RATIO,
       p.PURCHASE_QTY, p.PURCHASE_VALUE, r.DECLARED_SALES_KG SUPPLIER_QTY,
       COALESCE(b.INFLOW,0) INFLOW, COALESCE(b.OUTFLOW,0) OUTFLOW,
       CASE WHEN s3.LINKED_FACTORY_ID=m.FACTORY_ID THEN 1 ELSE 0 END LOOP_FOUND,
       LAG(m.CLOSING_STOCK) OVER(PARTITION BY m.FACTORY_ID ORDER BY m.PERIOD_MONTH) PREVIOUS_CLOSING,
       LAG(m.PRODUCT) OVER(PARTITION BY m.FACTORY_ID ORDER BY m.PERIOD_MONTH) PREVIOUS_PRODUCT,
       AVG(m.OPERATING_HOURS) OVER(PARTITION BY m.FACTORY_ID ORDER BY m.PERIOD_MONTH ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING) PRIOR_HOURS_BASELINE,
       AVG(m.POWER_KWH/NULLIF(m.DECLARED_OUTPUT,0)) OVER(PARTITION BY m.FACTORY_ID ORDER BY m.PERIOD_MONTH ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING) PRIOR_POWER_BASELINE
FROM GST_EVIDENCE.FACTORY_MONTH m
LEFT JOIN (SELECT FACTORY_ID, PERIOD_MONTH, SUM(QUANTITY) INVOICE_QTY, SUM(INVOICE_VALUE) INVOICE_VALUE FROM GST_EVIDENCE.INVOICES GROUP BY FACTORY_ID, PERIOD_MONTH) i ON i.FACTORY_ID=m.FACTORY_ID AND i.PERIOD_MONTH=m.PERIOD_MONTH
LEFT JOIN (SELECT FACTORY_ID, PERIOD_MONTH, SUM(QUANTITY) DISPATCH_QTY, 1.0-COUNT(DISTINCT EWAY_ID)*1.0/COUNT(*) REUSE_RATIO FROM GST_EVIDENCE.EWAY_BILLS GROUP BY FACTORY_ID, PERIOD_MONTH) e ON e.FACTORY_ID=m.FACTORY_ID AND e.PERIOD_MONTH=m.PERIOD_MONTH
LEFT JOIN (SELECT BUYER_FACTORY_ID, PERIOD_MONTH, SUM(QUANTITY) PURCHASE_QTY, SUM(INVOICE_VALUE) PURCHASE_VALUE FROM GST_EVIDENCE.PURCHASE_INVOICES GROUP BY BUYER_FACTORY_ID, PERIOD_MONTH) p ON p.BUYER_FACTORY_ID=m.FACTORY_ID AND p.PERIOD_MONTH=m.PERIOD_MONTH
LEFT JOIN GST_EVIDENCE.SUPPLIERS s ON s.OWNER_FACTORY_ID=m.FACTORY_ID
LEFT JOIN GST_EVIDENCE.SUPPLIER_RETURNS r ON r.SUPPLIER_ID=s.SUPPLIER_ID AND r.PERIOD_MONTH=m.PERIOD_MONTH
LEFT JOIN GST_EVIDENCE.SUPPLIERS s2 ON s2.OWNER_FACTORY_ID=s.LINKED_FACTORY_ID
LEFT JOIN GST_EVIDENCE.SUPPLIERS s3 ON s3.OWNER_FACTORY_ID=s2.LINKED_FACTORY_ID
LEFT JOIN (SELECT FACTORY_ID, PERIOD_MONTH, SUM(CASE WHEN DIRECTION='in' THEN AMOUNT ELSE 0 END) INFLOW, SUM(CASE WHEN DIRECTION='out' THEN AMOUNT ELSE 0 END) OUTFLOW FROM GST_EVIDENCE.BANK_ENTRIES GROUP BY FACTORY_ID, PERIOD_MONTH) b ON b.FACTORY_ID=m.FACTORY_ID AND b.PERIOD_MONTH=m.PERIOD_MONTH;

CREATE OR REPLACE VIEW GST_EVIDENCE.V_FEATURES AS
SELECT FACTORY_ID, PERIOD_MONTH, 'material_output' CHECK_FAMILY, 'production' SOURCE_FAMILY,
       PURCHASES_KG*.8 EXPECTED, DECLARED_OUTPUT OBSERVED, PURCHASES_KG*.8-DECLARED_OUTPUT GAP,
       GREATEST(ABS(PURCHASES_KG*.8-DECLARED_OUTPUT)/NULLIF(PURCHASES_KG*.8,0), ABS(POWER_KWH/4-DECLARED_OUTPUT)/NULLIF(POWER_KWH/4,0)) SEVERITY,
       'material kg='||PURCHASES_KG||', power kWh='||POWER_KWH||', hours='||OPERATING_HOURS||', raw stock change='||RAW_STOCK_CHANGE EVIDENCE,
       CASE WHEN ABS(POWER_KWH/4-DECLARED_OUTPUT)/NULLIF(POWER_KWH/4,0)>.08 THEN 'contradicting evidence' ELSE 'needs human review' END DISCREPANCY_CLASS
FROM GST_EVIDENCE.V_LEDGER
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH, 'dispatch_invoice','movement',DISPATCH_QTY,COALESCE(INVOICE_QTY,0),DISPATCH_QTY-COALESCE(INVOICE_QTY,0),
       GREATEST(ABS(DISPATCH_QTY-COALESCE(INVOICE_QTY,0))/NULLIF(DISPATCH_QTY,0),REUSE_RATIO),
       'document reuse fraction='||REUSE_RATIO,
       CASE WHEN INVOICE_QTY IS NULL THEN 'missing documents' ELSE 'mismatch' END
FROM GST_EVIDENCE.V_LEDGER
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH,'stock_rollforward','production',OPENING_STOCK+PURCHASES_FINISHED+DECLARED_OUTPUT-DECLARED_DISPATCH,CLOSING_STOCK,
       OPENING_STOCK+PURCHASES_FINISHED+DECLARED_OUTPUT-DECLARED_DISPATCH-CLOSING_STOCK,
       GREATEST(ABS(OPENING_STOCK+PURCHASES_FINISHED+DECLARED_OUTPUT-DECLARED_DISPATCH-CLOSING_STOCK),ABS(OPENING_STOCK-COALESCE(PREVIOUS_CLOSING,OPENING_STOCK)))/NULLIF(DECLARED_OUTPUT,0),
       'previous closing='||COALESCE(PREVIOUS_CLOSING,OPENING_STOCK),'mismatch'
FROM GST_EVIDENCE.V_LEDGER
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH,'supplier_chain','supplier',PURCHASE_QTY,COALESCE(SUPPLIER_QTY,0),PURCHASE_QTY-COALESCE(SUPPLIER_QTY,0),
       ABS(PURCHASE_QTY-COALESCE(SUPPLIER_QTY,0))/NULLIF(PURCHASE_QTY,0),'three-party cycle='||LOOP_FOUND,
       CASE WHEN SUPPLIER_QTY IS NULL THEN 'missing documents' ELSE 'supplier issue' END
FROM GST_EVIDENCE.V_LEDGER
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH,'bank_sales','financial',INVOICE_VALUE,INFLOW,INFLOW-INVOICE_VALUE,
       ABS(INFLOW-INVOICE_VALUE)/GREATEST(INFLOW,INVOICE_VALUE,1),'invoice value compared with receipts','needs human review'
FROM GST_EVIDENCE.V_LEDGER
UNION ALL
SELECT FACTORY_ID, PERIOD_MONTH,'bank_purchases','financial',PURCHASE_VALUE,OUTFLOW,OUTFLOW-PURCHASE_VALUE,
       ABS(OUTFLOW-PURCHASE_VALUE)/GREATEST(OUTFLOW,PURCHASE_VALUE,1),'purchase value compared with payments','needs human review'
FROM GST_EVIDENCE.V_LEDGER;

CREATE OR REPLACE VIEW GST_EVIDENCE.V_ALL_EVIDENCE AS SELECT f.* FROM GST_EVIDENCE.V_FEATURES f CROSS JOIN GST_EVIDENCE.SETTINGS s WHERE f.SEVERITY>s.THRESHOLD;
CREATE OR REPLACE VIEW GST_EVIDENCE.V_MATERIAL_OUTPUT AS SELECT * FROM GST_EVIDENCE.V_ALL_EVIDENCE WHERE CHECK_FAMILY='material_output';
CREATE OR REPLACE VIEW GST_EVIDENCE.V_DISPATCH_INVOICE AS SELECT * FROM GST_EVIDENCE.V_ALL_EVIDENCE WHERE CHECK_FAMILY='dispatch_invoice';
CREATE OR REPLACE VIEW GST_EVIDENCE.V_STOCK_ROLLFORWARD AS SELECT * FROM GST_EVIDENCE.V_ALL_EVIDENCE WHERE CHECK_FAMILY='stock_rollforward';
CREATE OR REPLACE VIEW GST_EVIDENCE.V_SUPPLIER_LOOP AS SELECT * FROM GST_EVIDENCE.V_ALL_EVIDENCE WHERE CHECK_FAMILY='supplier_chain';
CREATE OR REPLACE VIEW GST_EVIDENCE.V_RANKED_CASES AS
SELECT m.FACTORY_ID,m.PERIOD_MONTH,COALESCE(a.SIGNAL_COUNT,0) SIGNAL_COUNT,COALESCE(a.EVIDENCE_COUNT,0) EVIDENCE_COUNT,
       COALESCE(a.SCORE,0) TOTAL_ABSOLUTE_GAP,
       CASE WHEN a.SIGNAL_COUNT>=2 THEN 'prioritise' WHEN a.SIGNAL_COUNT=1 THEN 'review only' ELSE 'clear' END STATUS
FROM GST_EVIDENCE.FACTORY_MONTH m LEFT JOIN (
 SELECT FACTORY_ID,PERIOD_MONTH,COUNT(*) SIGNAL_COUNT,SUM(N) EVIDENCE_COUNT,SUM(SEVERITY) SCORE
 FROM (SELECT FACTORY_ID,PERIOD_MONTH,SOURCE_FAMILY,COUNT(*) N,MAX(SEVERITY) SEVERITY FROM GST_EVIDENCE.V_ALL_EVIDENCE GROUP BY FACTORY_ID,PERIOD_MONTH,SOURCE_FAMILY)
 GROUP BY FACTORY_ID,PERIOD_MONTH
) a ON a.FACTORY_ID=m.FACTORY_ID AND a.PERIOD_MONTH=m.PERIOD_MONTH;

-- A single source family is excluded from prioritisation and this disposition is
-- evidence based and any taxpayer explanation stays outside the detection SQL.
CREATE OR REPLACE VIEW GST_EVIDENCE.V_SINGLE_SIGNAL_DISPOSITIONS AS
SELECT r.FACTORY_ID,r.PERIOD_MONTH,r.SIGNAL_COUNT,r.STATUS,
       COALESCE(a.SOURCE_FAMILY,'none') SOURCE_FAMILY,
       CASE
         WHEN r.SIGNAL_COUNT<>1 THEN 'Not applicable: corroborated or no signal'
         WHEN a.SOURCE_FAMILY='production' AND u.FACTORY_ID IS NOT NULL THEN 'Cleared: documented machinery change'
         WHEN a.SOURCE_FAMILY='production' AND l.PREVIOUS_PRODUCT IS NOT NULL AND l.PREVIOUS_PRODUCT<>l.PRODUCT THEN 'Cleared: documented product mix change'
         WHEN a.SOURCE_FAMILY='production' AND l.PRIOR_HOURS_BASELINE IS NOT NULL AND l.OPERATING_HOURS>l.PRIOR_HOURS_BASELINE*1.2 THEN 'Cleared: documented longer operating hours'
         WHEN a.SOURCE_FAMILY='production' AND l.RAW_STOCK_CHANGE>0 THEN 'Cleared: documented seasonal stock build'
         ELSE 'Review-only: unexplained'
       END DISPOSITION
FROM GST_EVIDENCE.V_RANKED_CASES r
LEFT JOIN GST_EVIDENCE.V_LEDGER l ON l.FACTORY_ID=r.FACTORY_ID AND l.PERIOD_MONTH=r.PERIOD_MONTH
LEFT JOIN (
 SELECT FACTORY_ID,PERIOD_MONTH,MIN(SOURCE_FAMILY) SOURCE_FAMILY
 FROM GST_EVIDENCE.V_ALL_EVIDENCE
 GROUP BY FACTORY_ID,PERIOD_MONTH
) a ON a.FACTORY_ID=r.FACTORY_ID AND a.PERIOD_MONTH=r.PERIOD_MONTH
LEFT JOIN (SELECT FACTORY_ID,INSTALLED_MONTH FROM GST_EVIDENCE.MACHINES GROUP BY FACTORY_ID,INSTALLED_MONTH) u ON u.FACTORY_ID=r.FACTORY_ID AND u.INSTALLED_MONTH=r.PERIOD_MONTH;
