CREATE OR REPLACE TABLE GST_EVIDENCE.ENTITY_KEYS AS
SELECT 'factory' AS ENTITY_TYPE, FACTORY_ID AS ENTITY_ID,
       REGEXP_REPLACE(UPPER(ADDRESS), '[^A-Z0-9]', '') AS ADDRESS_KEY,
       REGEXP_REPLACE(PHONE, '[^0-9]', '') AS PHONE_KEY,
       REGEXP_REPLACE(UPPER(VEHICLE_PLATE), '[^A-Z0-9]', '') AS VEHICLE_KEY
FROM GST_EVIDENCE.FACTORIES
UNION ALL
SELECT 'supplier' AS ENTITY_TYPE, SUPPLIER_ID AS ENTITY_ID,
       REGEXP_REPLACE(UPPER(ADDRESS), '[^A-Z0-9]', '') AS ADDRESS_KEY,
       REGEXP_REPLACE(PHONE, '[^0-9]', '') AS PHONE_KEY,
       CAST(NULL AS VARCHAR(20)) AS VEHICLE_KEY
FROM GST_EVIDENCE.SUPPLIERS;
