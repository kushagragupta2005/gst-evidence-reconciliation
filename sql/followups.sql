-- Example guarded dashboard query: "Show the dispatch gap by month."
SELECT PERIOD_MONTH,
       COUNT(*) AS FACTORY_COUNT,
       SUM(ABS(GAP)) AS TOTAL_ABSOLUTE_DISPATCH_GAP
FROM GST_EVIDENCE.V_DISPATCH_INVOICE
GROUP BY PERIOD_MONTH
ORDER BY PERIOD_MONTH;

-- Example: show all evidence for one ranked factory and period.
SELECT e.FACTORY_ID, e.PERIOD_MONTH, e.CHECK_FAMILY, e.EXPECTED, e.OBSERVED,
       e.GAP, e.EVIDENCE, e.DISCREPANCY_CLASS
FROM GST_EVIDENCE.V_ALL_EVIDENCE e
WHERE e.FACTORY_ID = 'F000001'
ORDER BY e.PERIOD_MONTH, e.CHECK_FAMILY;
